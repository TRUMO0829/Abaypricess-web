import type { Assessment, ScaleQuestion } from "@/types/assessment"

/*
 * Байгууллагын үнэлгээний асуулга.
 *
 * Асуулт нэмэх:
 *   - Бүлэг (section) бүр асуулгын нэг алхам болно. Бүлгийн тоо, асуултын тоо хязгааргүй (ж: 360).
 *   - Асуултын `id` давтагдахгүй, нийтэлсний дараа өөрчлөхгүй (хадгалсан хариулт id-аар холбогдоно).
 *   - Асуулт бүр өөрийн `weight` (жин)-тэй; default 1. 0 бол оноонд орохгүй.
 *   - Төрлүүд: `scale` (1–5 гэх мэт), `yesno`, `choice` (сонголт бүр өөр оноотой), `text` (оноогүй).
 *   - Асуулт нэмэх/хасах, жин өөрчлөх бүрт `version`-ийг ахиулна.
 *
 * TODO: жишээ асуултууд — захиалагчийн 360 асуултаар солино.
 */

/** «Санал нийлэх» 1–5 шатлал — ихэнх асуултад ашиглах товчлол */
function agree(id: string, text: string, options: Partial<Omit<ScaleQuestion, "id" | "text" | "type">> = {}): ScaleQuestion {
  return {
    id,
    text,
    type: "scale",
    min: 1,
    max: 5,
    minLabel: "Огт санал нийлэхгүй",
    maxLabel: "Бүрэн санал нийлнэ",
    ...options,
  }
}

